"""Write docs/module-interfaces.md: every module's public interface (NFR-07).

For each module in ``app.modules.ALLOWED_DEPENDENCIES`` it lists the tables the module
owns, the services it may call, the events it publishes and subscribes to, and every
public name of its ``service.py`` with its signature and the first line of its
docstring. Run after changing a service::

    python scripts/export_interfaces.py

``tests/test_maintainability.py`` fails when the committed file is out of date, so an
interface change always shows up in review, like the API contract does.
"""

import ast
import enum
import importlib
import inspect
import re
import sys
from dataclasses import fields, is_dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "module-interfaces.md"
sys.path.insert(0, str(ROOT))

from app.core.database import Base  # noqa: E402
from app.modules import ALLOWED_DEPENDENCIES  # noqa: E402
from scripts.affected_modules import _event_calls  # noqa: E402

HEADER = """# Module interfaces

Generated by `python scripts/export_interfaces.py` from each module's `__init__.py` and
`service.py`; do not edit by hand. A module's other code may only use what is listed
here for the modules it may call (`docs/architecture.md`, "Module rules"). Each module's
README describes its routes and rules in more detail.
"""


def _first_line(obj) -> str:
    # The object's own docstring only: an enum or model must not show its base class's.
    own = obj.__dict__.get("__doc__") if inspect.isclass(obj) else obj.__doc__
    doc = inspect.cleandoc(own) if own else ""
    paragraph = doc.split("\n\n")[0]
    return " ".join(paragraph.split())


def _signature(obj) -> str:
    """The signature as written in the source, so the file is the same on every run."""
    node = ast.parse(inspect.cleandoc("\n" + inspect.getsource(obj))).body[0]
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"({ast.unparse(node.args)}){returns}"


def _owned_by(module: str, obj) -> bool:
    return getattr(obj, "__module__", "").startswith(f"app.modules.{module}")


def _entry(name: str, obj) -> str:
    summary = _first_line(obj)
    if inspect.isclass(obj) and issubclass(obj, enum.Enum):
        values = ", ".join(f"`{m.value}`" for m in obj)
        return f"- **`{name}`** (enum: {values}){': ' + summary if summary else ''}"
    if inspect.isclass(obj) and is_dataclass(obj):
        names = ", ".join(f.name for f in fields(obj))
        return f"- **`{name}`** (dataclass: {names}): {summary}"
    if inspect.isclass(obj):
        kind = "exception" if issubclass(obj, BaseException) else "class"
        return f"- **`{name}`** ({kind}): {summary}"
    if callable(obj):
        return f"- **`{name}{_signature(obj)}`**: {summary}"
    return f"- **`{name}`** = `{obj!r}`"


def _header_line(doc: str, key: str) -> str:
    """The text after ``key:`` in a module docstring, up to the next field."""
    match = re.search(
        rf"{key}:\s*(.*?)(?=\n(?:Owns tables|Public interface|May call)|\n\n|\Z)", doc, re.S
    )
    text = " ".join(match.group(1).split()) if match else ""
    return re.split(r"(?<=\.)\s", text)[0].rstrip(".")


def render() -> str:
    parts = [HEADER]
    for module in sorted(ALLOWED_DEPENDENCIES):
        package = importlib.import_module(f"app.modules.{module}")
        service = importlib.import_module(f"app.modules.{module}.service")
        doc = inspect.getdoc(package) or ""
        title = doc.split("\n")[0]
        deps = ", ".join(f"`{d}`" for d in sorted(ALLOWED_DEPENDENCIES[module])) or "none"
        publishes = ", ".join(f"`{e}`" for e in sorted(_event_calls(module, "publish")))
        subscribes = ", ".join(f"`{e}`" for e in sorted(_event_calls(module, "subscribe")))
        parts.append(f"\n## {module}\n\n{title}\n")
        parts.append(f"- Owns tables: {_header_line(doc, 'Owns tables')}")
        parts.append(f"- May call: {deps}")
        if publishes:
            parts.append(f"- Publishes events: {publishes}")
        if subscribes:
            parts.append(f"- Subscribes to: {subscribes}")
        parts.append(f"\n`app.modules.{module}.service`:\n")
        names = [
            n
            for n in _public_names(service)
            if _owned_by(module, getattr(service, n)) or n in _reexported(module)
        ]
        parts += [_entry(n, getattr(service, n)) for n in names]
    return "\n".join(parts) + "\n"


def _public_names(service) -> list[str]:
    return sorted(
        n
        for n, obj in vars(service).items()
        if not n.startswith("_") and not inspect.ismodule(obj) and _is_interface(obj)
    )


def _is_interface(obj) -> bool:
    if inspect.isclass(obj):
        # ORM models are a module's private storage, never part of its interface.
        return not issubclass(obj, Base)
    return inspect.isfunction(obj) or isinstance(obj, (str, int, float))


def _reexported(module: str) -> set[str]:
    """Names ``service.py`` imports from its own package to offer them to callers."""
    tree = ast.parse((ROOT / "app" / "modules" / module / "service.py").read_text())
    names = set()
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith(
            f"app.modules.{module}"
        ):
            names.update(alias.asname or alias.name for alias in node.names)
    return names


def main() -> None:
    OUTPUT.write_text(render())
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
