"""Adaptive difficulty constrained to the selected topic (S07.2, FR-07).

Rules (pure, in ``level_after``):

* three correct answers in a row raise the next question's difficulty one level;
* two incorrect answers in a row lower it one level;
* the streak restarts after every change, and the level stays within easy..hard.

Each next question is taken from the published bank for the selected subject and
topic at the current level, or, when the bank has none left, generated by the LLM
for that subject, topic and level. Generated items carrying any other topic are
rejected and regenerated (``generation.request_items``), and every question is
checked against the selected topic again before it is served, so containment holds
at every level reached. AI questions made here are stored as drafts: they serve this
attempt only and never reach the bank without review.

Answers are scored by the quizzes module's deterministic scoring, never by the LLM.
"""

from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.modules.llm.generation import (
    GenerationFailedError,
    request_items,
    same_text,
)
from app.modules.llm.models import AdaptiveSession, LlmTask
from app.modules.llm.provider import LlmProvider
from app.modules.questions import service as questions
from app.modules.questions.service import (
    Difficulty,
    QuestionSource,
    QuestionType,
)
from app.modules.quizzes import service as quizzes

LEVELS = (Difficulty.EASY, Difficulty.MEDIUM, Difficulty.HARD)
RAISE_AFTER_CORRECT = 3
LOWER_AFTER_INCORRECT = 2
MIN_LENGTH, MAX_LENGTH, DEFAULT_LENGTH = 5, 20, 10
_SERVABLE = {QuestionType.MULTIPLE_CHOICE, QuestionType.TRUE_FALSE}


class NoQuestionAvailableError(Exception):
    """The bank has nothing left at this level and no LLM is configured."""


class AnswerRefusedError(Exception):
    pass


@dataclass(frozen=True)
class Level:
    difficulty: Difficulty
    correct_streak: int
    incorrect_streak: int


def level_after(start: Difficulty, results: list[bool]) -> Level:
    """The difficulty for the next question after ``results`` (oldest first)."""
    index, correct, incorrect = LEVELS.index(start), 0, 0
    for ok in results:
        correct, incorrect = (correct + 1, 0) if ok else (0, incorrect + 1)
        if correct >= RAISE_AFTER_CORRECT:
            index, correct = min(index + 1, len(LEVELS) - 1), 0
        elif incorrect >= LOWER_AFTER_INCORRECT:
            index, incorrect = max(index - 1, 0), 0
    return Level(LEVELS[index], correct, incorrect)


@dataclass(frozen=True)
class CurrentQuestion:
    question_id: int
    position: int
    text: str
    question_type: QuestionType
    options: tuple[str, ...]
    subject: str
    topic: str
    difficulty: Difficulty
    source: QuestionSource


@dataclass(frozen=True)
class ServedSummary:
    question_id: int
    position: int
    topic: str
    difficulty: Difficulty
    correct: bool | None


@dataclass(frozen=True)
class AdaptiveState:
    id: int
    user_id: int
    subject: str
    topic: str
    start_difficulty: Difficulty
    question_count: int
    answered_count: int
    level: Level
    finished: bool
    current: CurrentQuestion | None
    history: tuple[ServedSummary, ...]
    outcome: quizzes.AttemptOutcome | None


@dataclass(frozen=True)
class Feedback:
    correct: bool
    correct_answer: str | None
    explanation: str | None
    previous_difficulty: Difficulty
    state: AdaptiveState

    @property
    def change(self) -> str | None:
        before = LEVELS.index(self.previous_difficulty)
        after = LEVELS.index(self.state.level.difficulty)
        return None if before == after else ("raised" if after > before else "lowered")


def _session(db: Session, session_id: int) -> AdaptiveSession:
    session = db.get(AdaptiveSession, session_id)
    if session is None:
        raise LookupError(f"adaptive session {session_id} not found")
    return session


def owner_of(db: Session, session_id: int) -> int | None:
    session = db.get(AdaptiveSession, session_id)
    return session.user_id if session else None


def _on_topic(session: AdaptiveSession, view: questions.QuestionView) -> bool:
    return same_text(view.topic, session.topic) and same_text(view.subject, session.subject)


def start(
    db: Session,
    *,
    user_id: int,
    subject: str,
    topic: str,
    start_difficulty: Difficulty,
    question_count: int,
    channel_id: int | None = None,
) -> int:
    """Create the adaptive quiz, its attempt and the session; returns the session id."""
    if not MIN_LENGTH <= question_count <= MAX_LENGTH:
        raise ValueError(f"question_count must be between {MIN_LENGTH} and {MAX_LENGTH}")
    quiz_id = quizzes.create_quiz(
        db,
        creator_id=user_id,
        title=f"Adaptive quiz: {topic}",
        subject=subject,
        topic=topic,
        difficulty=start_difficulty.value,
        duration_minutes=0,
        question_ids=[],
        channel_id=channel_id,
        publish=False,
        adaptive=True,
    )
    attempt_id = quizzes.start_attempt(db, quiz_id, user_id)
    session = AdaptiveSession(
        user_id=user_id,
        quiz_id=quiz_id,
        attempt_id=attempt_id,
        channel_id=channel_id,
        subject=subject,
        topic=topic,
        start_difficulty=start_difficulty.value,
        question_count=question_count,
    )
    db.add(session)
    db.flush()
    return session.id


def _pick_from_bank(
    db: Session, session: AdaptiveSession, level: Difficulty, used: set[int]
) -> int | None:
    for item in questions.quiz_candidates(
        db,
        subject=session.subject,
        topic=session.topic,
        difficulty=level,
        channel_id=session.channel_id,
    ):
        q = item.question
        if q.id not in used and q.question_type in _SERVABLE and _on_topic(session, q):
            return q.id
    return None


def _generate(
    db: Session,
    provider: LlmProvider,
    session: AdaptiveSession,
    level: Difficulty,
    served_count: int,
    used_texts: set[str],
) -> int:
    _, items = request_items(
        db,
        provider,
        user_id=session.user_id,
        task=LlmTask.ADAPT_DIFFICULTY,
        subject=session.subject,
        topic=session.topic,
        difficulty=level,
        count=1,
        channel_id=session.channel_id,
        offset=1000 + served_count,
        avoid=used_texts,
    )
    if not items:
        raise GenerationFailedError("no on-topic question was produced")
    item = items[0]
    return questions.create_question(
        db,
        author_id=session.user_id,
        subject=session.subject,
        topic=session.topic,
        difficulty=level,
        question_type=QuestionType.MULTIPLE_CHOICE,
        text=item.text,
        options=list(item.options),
        correct_answer=item.correct_answer,
        explanation=item.explanation,
        channel_id=session.channel_id,
        source=QuestionSource.LLM,  # a draft: never in the bank without review
    ).id


def _serve_next(db: Session, provider: LlmProvider | None, session: AdaptiveSession) -> None:
    history = quizzes.adaptive_history(db, session.attempt_id)
    if any(not s.answered for s in history) or len(history) >= session.question_count:
        return
    level = level_after(
        Difficulty(session.start_difficulty), [bool(s.is_correct) for s in history]
    ).difficulty
    used = {s.question_id for s in history}
    question_id = _pick_from_bank(db, session, level, used)
    if question_id is None:
        if provider is None:
            raise NoQuestionAvailableError(
                f"No more {level.value} questions on {session.topic} in the bank, and AI "
                "generation is not available."
            )
        texts = {v.text for v in questions.get_questions(db, used).values()}
        question_id = _generate(db, provider, session, level, len(history), texts)
    view = questions.get_questions(db, [question_id])[question_id]
    if not _on_topic(session, view) or view.difficulty is not level:
        raise GenerationFailedError("question outside the selected topic or level")
    quizzes.add_quiz_question(db, session.quiz_id, question_id)


def state(
    db: Session, session_id: int, *, serve: bool = False, provider: LlmProvider | None = None
) -> AdaptiveState:
    """The session as its owner sees it.

    With ``serve`` the next question is chosen first if none is waiting (from the bank,
    else generated with ``provider``); that may raise ``GenerationFailedError`` or
    ``NoQuestionAvailableError``, leaving every answer already given intact.
    """
    session = _session(db, session_id)
    outcome = quizzes.attempt_outcome(db, session.attempt_id)
    if serve and outcome is None:
        _serve_next(db, provider, session)
    history = quizzes.adaptive_history(db, session.attempt_id)
    answered = [s for s in history if s.answered]
    level = level_after(
        Difficulty(session.start_difficulty), [bool(s.is_correct) for s in answered]
    )
    waiting = next((s for s in history if not s.answered), None)
    current = None
    if waiting is not None and outcome is None:
        view = questions.get_questions(db, [waiting.question_id])[waiting.question_id]
        bank = questions.get_bank_question(db, waiting.question_id)
        current = CurrentQuestion(
            question_id=view.id,
            position=waiting.position,
            text=view.text,
            question_type=view.question_type,
            options=view.options,
            subject=view.subject,
            topic=view.topic,
            difficulty=view.difficulty,
            source=bank.source,
        )
    return AdaptiveState(
        id=session.id,
        user_id=session.user_id,
        subject=session.subject,
        topic=session.topic,
        start_difficulty=Difficulty(session.start_difficulty),
        question_count=session.question_count,
        answered_count=len(answered),
        level=level,
        finished=outcome is not None,
        current=current,
        history=tuple(
            ServedSummary(
                question_id=s.question_id,
                position=s.position,
                topic=s.topic,
                difficulty=Difficulty(s.difficulty),
                correct=s.is_correct if s.answered else None,
            )
            for s in history
        ),
        outcome=outcome,
    )


def answer(db: Session, session_id: int, question_id: int, response: str) -> Feedback:
    """Score the answer, update the level and close the quiz after the last question.

    Serving the next question is left to ``state`` so a provider failure there can
    never lose this committed answer.
    """
    session = _session(db, session_id)
    before = state(db, session_id).level.difficulty
    try:
        result = quizzes.answer_adaptive(db, session.attempt_id, question_id, response)
    except quizzes.AdaptiveAnswerError as exc:
        raise AnswerRefusedError(str(exc)) from None
    history = quizzes.adaptive_history(db, session.attempt_id)
    if len(history) >= session.question_count and all(s.answered for s in history):
        quizzes.finish_attempt(db, session.attempt_id)
    return Feedback(
        correct=result.is_correct,
        correct_answer=result.correct_answer,
        explanation=result.explanation,
        previous_difficulty=before,
        state=state(db, session_id),
    )


def sessions_for(db: Session, user_id: int) -> list[int]:
    return list(
        db.scalars(
            select(AdaptiveSession.id)
            .where(AdaptiveSession.user_id == user_id)
            .order_by(AdaptiveSession.id.desc())
        )
    )
